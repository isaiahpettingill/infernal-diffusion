import { MAX_BYTES } from './core.mjs';
import { decodePNG } from './png.mjs';
const root = document.querySelector('[data-trustmark]');
if (root) {
  const file = root.querySelector('input'), button = root.querySelector('[data-detect]');
  const reset = root.querySelector('[data-reset]'), status = root.querySelector('[role=status]');
  let revision = 0, busy = false;
  function changed() {
    revision++;
    button.disabled = busy || !file.files.length;
    status.textContent = file.files.length ? 'Ready. Detection downloads the runtime and models, then checks locally.' : 'Choose a PNG spritesheet to check.';
  }
  file.addEventListener('change', changed);
  reset.addEventListener('click', () => { file.value = ''; changed(); });
  button.addEventListener('click', async () => {
    if (busy || !file.files.length) return;
    const selected = file.files[0], version = ++revision;
    busy = true; button.disabled = true;
    try {
      if (selected.size > MAX_BYTES) throw new Error('PNG must be no larger than 16 MiB.');
      status.textContent = 'Reading raw PNG pixels…';
      const pixels = await decodePNG(await selected.arrayBuffer());
      if (version !== revision) return;
      status.textContent = 'Loading TrustMark and checking locally… The first check may take a minute.';
      const { detect } = await import('./detector.mjs');
      if (version !== revision) return;
      const result = await detect(pixels);
      if (version !== revision) return;
      status.textContent = {
        match: 'Infernal Diffusion marker detected (TrustMark Q, INFRNL1). This is a public marker, not cryptographic proof of origin.',
        other: 'A TrustMark watermark was detected, but it does not match the Infernal Diffusion marker.',
        absent: 'No Infernal Diffusion marker detected. Unmarked, edited, or degraded images can still have been generated by Infernal Diffusion.',
      }[result];
    } catch (error) {
      if (version === revision) status.textContent = `Could not check this image: ${error.message || error}. No detection result is available. Use a WebGPU-capable browser on HTTPS or localhost, and check your connection if model loading failed.`;
    } finally {
      busy = false; button.disabled = !file.files.length;
    }
  });
}
